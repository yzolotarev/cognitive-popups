/// (Typst, Unicode) for a symbol command.
pub fn symbol(name: &str) -> Option<(&'static str, &'static str)> {
    SYMBOLS
        .iter()
        .find(|(n, ..)| *n == name)
        .map(|(_, typst, unicode)| (*typst, *unicode))
}
