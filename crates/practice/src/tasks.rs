//! Whole tasks the reader left unfinished (route «продолжить задачу», B64).
//!
//! A [Собери вместе] task is kept with the reader's draft attempt, so Alt+T can
//! reopen it: the condition and the draft come back, the worked solution stays
//! hidden until the reader has an attempt. Nothing here grades anything and
//! nothing reaches FSRS (INV-02: «завершил» is not `Good`).
//!
//! The reader's actions only: a task is saved when the reader presses
//! [Отложить] or closes the window with a draft, finished by [Готово], and
//! dropped by [Не возвращаться], which [Вернуть] undoes (INV-12). Nothing is
//! deleted and nothing expires by itself.

use std::path::Path;

use rusqlite::{Connection, OptionalExtension, params};
use serde::Serialize;

#[derive(Debug, thiserror::Error)]
pub enum TaskError {
    #[error("database error: {0}")]
    Database(#[from] rusqlite::Error),
    #[error("task {0} not found")]
    NotFound(i64),
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum TaskStatus {
    Open,
    Done,
    Dropped,
}

impl TaskStatus {
    fn as_str(self) -> &'static str {
        match self {
            TaskStatus::Open => "open",
            TaskStatus::Done => "done",
            TaskStatus::Dropped => "dropped",
        }
    }

    fn parse(value: &str) -> Self {
        match value {
            "done" => TaskStatus::Done,
            "dropped" => TaskStatus::Dropped,
            _ => TaskStatus::Open,
        }
    }
}

/// A task as generated by `whole_task`, without the reader's work.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NewTask {
    pub type_id: u8,
    pub type_title: String,
    /// The categories practised, as in [Собери вместе].
    pub operations: Vec<String>,
    pub condition: String,
    /// Hidden until the reader has an attempt.
    pub solution: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct SavedTask {
    pub id: i64,
    pub type_id: u8,
    pub type_title: String,
    pub operations: Vec<String>,
    pub condition: String,
    pub solution: String,
    pub draft: String,
    pub status: TaskStatus,
    pub saved_at: i64,
    pub updated_at: i64,
}

pub struct TaskStore {
    connection: Connection,
}

const COLUMNS: &str = "task_id, type_id, type_title, operations_json, condition, solution, draft,
                       status, saved_at, updated_at";

impl TaskStore {
    pub fn open(path: impl AsRef<Path>) -> Result<Self, TaskError> {
        Self::from_connection(Connection::open(path)?)
    }

    pub fn open_in_memory() -> Result<Self, TaskError> {
        Self::from_connection(Connection::open_in_memory()?)
    }

    fn from_connection(connection: Connection) -> Result<Self, TaskError> {
        connection.busy_timeout(std::time::Duration::from_secs(5))?;
        connection.execute_batch(
            "CREATE TABLE IF NOT EXISTS practice_tasks (
                 task_id         INTEGER PRIMARY KEY AUTOINCREMENT,
                 key             TEXT NOT NULL UNIQUE,
                 type_id         INTEGER NOT NULL,
                 type_title      TEXT NOT NULL,
                 operations_json TEXT NOT NULL,
                 condition       TEXT NOT NULL,
                 solution        TEXT NOT NULL,
                 draft           TEXT NOT NULL DEFAULT '',
                 status          TEXT NOT NULL DEFAULT 'open'
                                 CHECK (status IN ('open', 'done', 'dropped')),
                 saved_at        INTEGER NOT NULL,
                 updated_at      INTEGER NOT NULL
             );",
        )?;
        Ok(Self { connection })
    }

    /// Keeps a task with the reader's draft. The same key twice is one task
    /// (INV-04): the repeat only updates the draft of a task still open.
    pub fn save(
        &mut self,
        key: &str,
        task: &NewTask,
        draft: &str,
        now: i64,
    ) -> Result<i64, TaskError> {
        let operations = serde_json::to_string(&task.operations).unwrap_or_else(|_| "[]".into());
        self.connection.execute(
            "INSERT INTO practice_tasks
                 (key, type_id, type_title, operations_json, condition, solution, draft,
                  saved_at, updated_at)
             VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?8, ?8)
             ON CONFLICT (key) DO UPDATE SET draft = ?7, updated_at = ?8
             WHERE status = 'open'",
            params![
                key,
                task.type_id,
                task.type_title,
                operations,
                task.condition,
                task.solution,
                draft,
                now
            ],
        )?;
        Ok(self.connection.query_row(
            "SELECT task_id FROM practice_tasks WHERE key = ?1",
            [key],
            |r| r.get(0),
        )?)
    }

    pub fn set_draft(&mut self, id: i64, draft: &str, now: i64) -> Result<(), TaskError> {
        let changed = self.connection.execute(
            "UPDATE practice_tasks SET draft = ?2, updated_at = ?3
             WHERE task_id = ?1 AND status = 'open'",
            params![id, draft, now],
        )?;
        must_exist(id, changed)
    }

    pub fn get(&self, id: i64) -> Result<Option<SavedTask>, TaskError> {
        Ok(self
            .connection
            .query_row(
                &format!("SELECT {COLUMNS} FROM practice_tasks WHERE task_id = ?1"),
                [id],
                from_row,
            )
            .optional()?)
    }

    /// The task to continue: the one worked on last.
    pub fn latest_open(&self) -> Result<Option<SavedTask>, TaskError> {
        Ok(self
            .connection
            .query_row(
                &format!(
                    "SELECT {COLUMNS} FROM practice_tasks WHERE status = 'open'
                     ORDER BY updated_at DESC, task_id DESC LIMIT 1"
                ),
                [],
                from_row,
            )
            .optional()?)
    }

    pub fn count_open(&self) -> Result<usize, TaskError> {
        let count: i64 = self.connection.query_row(
            "SELECT COUNT(*) FROM practice_tasks WHERE status = 'open'",
            [],
            |r| r.get(0),
        )?;
        Ok(count as usize)
    }

    /// [Готово]: the reader closed the task. Not a grade.
    pub fn finish(&mut self, id: i64, now: i64) -> Result<(), TaskError> {
        self.set_status(id, TaskStatus::Done, now)
    }

    /// [Не возвращаться]: the reader does not want this task again.
    pub fn drop_task(&mut self, id: i64, now: i64) -> Result<(), TaskError> {
        self.set_status(id, TaskStatus::Dropped, now)
    }

    /// [Вернуть]: undoes a drop, with the draft as it was.
    pub fn restore(&mut self, id: i64, now: i64) -> Result<(), TaskError> {
        let changed = self.connection.execute(
            "UPDATE practice_tasks SET status = 'open', updated_at = ?2
             WHERE task_id = ?1 AND status = 'dropped'",
            params![id, now],
        )?;
        must_exist(id, changed)
    }

    fn set_status(&mut self, id: i64, status: TaskStatus, now: i64) -> Result<(), TaskError> {
        let changed = self.connection.execute(
            "UPDATE practice_tasks SET status = ?2, updated_at = ?3 WHERE task_id = ?1",
            params![id, status.as_str(), now],
        )?;
        must_exist(id, changed)
    }
}

fn must_exist(id: i64, changed: usize) -> Result<(), TaskError> {
    if changed == 0 {
        return Err(TaskError::NotFound(id));
    }
    Ok(())
}

fn from_row(row: &rusqlite::Row<'_>) -> rusqlite::Result<SavedTask> {
    let operations: String = row.get(3)?;
    let status: String = row.get(7)?;
    Ok(SavedTask {
        id: row.get(0)?,
        type_id: row.get(1)?,
        type_title: row.get(2)?,
        operations: serde_json::from_str(&operations).unwrap_or_default(),
        condition: row.get(4)?,
        solution: row.get(5)?,
        draft: row.get(6)?,
        status: TaskStatus::parse(&status),
        saved_at: row.get(8)?,
        updated_at: row.get(9)?,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn task() -> NewTask {
        NewTask {
            type_id: 1,
            type_title: "Отработка метода".into(),
            operations: vec!["Шаг Ньютона".into()],
            condition: "Дано: f(x) = x² − 2.\nТребуется: сделать два шага.".into(),
            solution: "x₁ = 1,5; x₂ ≈ 1,4167".into(),
        }
    }

    #[test]
    fn a_saved_task_comes_back_with_its_draft_and_the_solution_kept_for_later() {
        let mut store = TaskStore::open_in_memory().unwrap();
        assert_eq!(store.latest_open().unwrap(), None);
        let id = store.save("op:1", &task(), "x₁ = 1,5", 100).unwrap();
        let back = store.latest_open().unwrap().unwrap();
        assert_eq!(back.id, id);
        assert_eq!(back.draft, "x₁ = 1,5");
        assert_eq!(back.operations, vec!["Шаг Ньютона"]);
        assert_eq!(back.status, TaskStatus::Open);
        assert!(!back.solution.is_empty());
    }

    #[test]
    fn inv04_the_same_key_is_one_task_and_only_the_draft_moves() {
        let mut store = TaskStore::open_in_memory().unwrap();
        let first = store.save("op:1", &task(), "a", 100).unwrap();
        let mut other = task();
        other.condition = "другая".into();
        let second = store.save("op:1", &other, "ab", 200).unwrap();
        assert_eq!(first, second);
        assert_eq!(store.count_open().unwrap(), 1);
        let kept = store.get(first).unwrap().unwrap();
        assert_eq!(kept.draft, "ab");
        assert!(
            kept.condition.starts_with("Дано"),
            "the first condition stays"
        );
        assert_eq!((kept.saved_at, kept.updated_at), (100, 200));
    }

    #[test]
    fn the_last_worked_task_is_offered_first() {
        let mut store = TaskStore::open_in_memory().unwrap();
        let old = store.save("a", &task(), "", 100).unwrap();
        let new = store.save("b", &task(), "", 200).unwrap();
        assert_eq!(store.latest_open().unwrap().unwrap().id, new);
        store.set_draft(old, "ещё думаю", 300).unwrap();
        assert_eq!(store.latest_open().unwrap().unwrap().id, old);
    }

    #[test]
    fn finished_and_dropped_tasks_leave_the_route_and_a_drop_can_be_undone() {
        let mut store = TaskStore::open_in_memory().unwrap();
        let id = store.save("a", &task(), "черновик", 100).unwrap();
        store.drop_task(id, 150).unwrap();
        assert_eq!(store.count_open().unwrap(), 0);
        assert_eq!(
            store.get(id).unwrap().unwrap().draft,
            "черновик",
            "a drop deletes nothing"
        );
        store.restore(id, 160).unwrap();
        assert_eq!(store.latest_open().unwrap().unwrap().draft, "черновик");
        store.finish(id, 170).unwrap();
        assert_eq!(store.count_open().unwrap(), 0);
        assert!(store.restore(id, 180).is_err(), "only a drop is undone");
        assert!(
            store.set_draft(id, "позже", 190).is_err(),
            "a finished task is not edited"
        );
        assert_eq!(store.get(id).unwrap().unwrap().status, TaskStatus::Done);
    }

    #[test]
    fn a_repeated_save_does_not_reopen_a_finished_task() {
        let mut store = TaskStore::open_in_memory().unwrap();
        let id = store.save("a", &task(), "x", 100).unwrap();
        store.finish(id, 110).unwrap();
        store.save("a", &task(), "y", 120).unwrap();
        let task = store.get(id).unwrap().unwrap();
        assert_eq!((task.status, task.draft.as_str()), (TaskStatus::Done, "x"));
    }

    #[test]
    fn an_unknown_task_is_an_error() {
        let mut store = TaskStore::open_in_memory().unwrap();
        assert!(matches!(store.finish(9, 1), Err(TaskError::NotFound(9))));
    }
}
