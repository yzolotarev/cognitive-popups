def example_prompt(
    material: str,
    query: str = "",
    intent: str = "",
    system_prompt: str = EXAMPLE_SYSTEM,
) -> list[dict[str, str]]:
    """A concrete example tied to the highlighted material.

    The reader's own request and their intent are optional and only appear when
    they explicitly chose them; the material is always the ground.
    """
    parts = [f"<MATERIAL>\n{material}\n</MATERIAL>"]
    if query.strip():
        parts.append(f"<USER_REQUEST>\n{query.strip()}\n</USER_REQUEST>")
    if intent.strip():
        parts.append(f"<INTENT>\n{intent.strip()}\n</INTENT>")
    return [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": "\n\n".join(parts)},
    ]


def reframe_prompt(
    material: str,
    focus: str = "",
    current_frame: str = "",
    system_prompt: str = REFRAME_SYSTEM,
) -> list[dict[str, str]]:
    """One alternative view: the source is the ground, the focus is optional.

    An empty focus is a real case, not a missing argument: it means "look at this
    yourself, I pressed the key", and the contract above says what to do then.
    """
    # JSON keeps the source and reader fields as data, even if they contain
    # strings that look like delimiters or chat roles.
    return [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": compact_json({
            "material": material, "focus": focus, "current_frame": current_frame,
        })},
    ]


def goal_prompt(
    material: str,
    direction: str = "",
    note: str = "",
    system_prompt: str = GOAL_SYSTEM,
) -> list[dict[str, str]]:
    """Turn a chosen direction into one concrete wording of the goal.

    The material is the ground; the direction and the reader's own words are
    optional data. Only the selected text is passed, never the whole journal.
    """
    parts = [f"<MATERIAL>\n{material}\n</MATERIAL>"]
    if direction.strip():
        parts.append(f"<DIRECTION>\n{direction.strip()}\n</DIRECTION>")
    if note.strip():
        parts.append(f"<READER_NOTE>\n{note.strip()}\n</READER_NOTE>")
    return [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": "\n\n".join(parts)},
    ]


def feynman_check_prompt(
    buffer_context: str,
    question: str,
    explanation: str,
    system_prompt: str = FEYNMAN_SYSTEM,
) -> list[dict[str, str]]:
    user = (
        f"<SOURCE_BUFFER>\n{buffer_context}\n</SOURCE_BUFFER>\n\n"
        f"<QUESTION>\n{question}\n</QUESTION>\n\n"
        f"<USER_EXPLANATION>\n{explanation}\n</USER_EXPLANATION>"
    )
    rubric = getattr(question, "rubric", "")
    if rubric:
        user += f"\n\n<HIDDEN_RUBRIC>\n{rubric}\n</HIDDEN_RUBRIC>"
    return [{"role": "system", "content": system_prompt}, {"role": "user", "content": user}]


def compact_json(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))
