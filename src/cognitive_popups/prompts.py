def clarify_question_prompt(
    buffer_context: str,
    question: str,
    system_prompt: str = CLARIFY_QUESTION_SYSTEM,
) -> list[dict[str, str]]:
    """The reader's own question, answered with the material as the ground.

    Unlike `clarify_prompt`, the question is not a word to be explained: it may
    ask for a connection the text only partly supports, so the answer has to say
    how it stands to the material instead of refusing when there is no verbatim
    support.
    """
    user = (
        f"<SOURCE_BUFFER>\n{buffer_context}\n</SOURCE_BUFFER>\n\n"
        f"<READER_QUESTION>\n{question}\n</READER_QUESTION>"
    )
    return [{"role": "system", "content": system_prompt}, {"role": "user", "content": user}]


def clarify_universe_prompt(
    source: str,
    question: str,
    mine: list[dict[str, str]],
    system_prompt: str = CLARIFY_UNIVERSE_SYSTEM,
    *,
    recent: str = "",
    step: str = "",
) -> list[dict[str, str]]:
    """Alt+C from the reader's own world: their passage, question and one past thought.

    `mine` holds the reader's own words verbatim (see universe.py); it is a hook
    for the explanation, never evidence about the text.
    """
    import json as _json

    # Order matters: surroundings first, the point last, right before the question.
    blocks = []
    if recent:
        blocks.append(f"<RECENT>\n{recent}\n</RECENT>")
    if step:
        blocks.append(f"<STEP>\n{step}\n</STEP>")
    blocks += [f"<SOURCE>\n{source}\n</SOURCE>",
               f"<QUESTION>\n{question}\n</QUESTION>",
               f"<MINE>\n{_json.dumps(mine, ensure_ascii=False)}\n</MINE>"]
    user = "\n\n".join(blocks)
    return [{"role": "system", "content": system_prompt}, {"role": "user", "content": user}]


