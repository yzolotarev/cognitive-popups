def clarify_prompt(
    buffer_context: str,
    terms: list[str],
    system_prompt: str = CLARIFY_SYSTEM,
) -> list[dict[str, str]]:
    user = (
        f"<SOURCE_BUFFER>\n{buffer_context}\n</SOURCE_BUFFER>\n\n"
        f"<UNKNOWN_TERMS>\n{', '.join(terms)}\n</UNKNOWN_TERMS>"
    )
    return [{"role": "system", "content": system_prompt}, {"role": "user", "content": user}]


def clarify_question_prompt(
    buffer_context: str,
    question: str,
    system_prompt: str = CLARIFY_QUESTION_SYSTEM,
) -> list[dict[str, str]]:
    """The reader's own question, answered with the material as the ground.

    Unlike `clarify_prompt`, the question is not a word to be explained: it may
    ask for a connection the text only partly supports, so the answer has to say
    how it stands to the material instead of refusing when there is no verbatim
    support.
    """
    user = (
        f"<SOURCE_BUFFER>\n{buffer_context}\n</SOURCE_BUFFER>\n\n"
        f"<READER_QUESTION>\n{question}\n</READER_QUESTION>"
    )
    return [{"role": "system", "content": system_prompt}, {"role": "user", "content": user}]


